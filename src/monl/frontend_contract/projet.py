"""Les deux documents d'accueil déposés dans le projet compilé.

`AGENTS.md` cadre la session d'une IA qui travaille SUR un site produit —
à ne pas confondre avec le CLAUDE.md du dépôt monl lui-même. `README.md`
s'adresse à l'humain qui vient d'ouvrir l'archive et cherche comment la
démarrer : la page d'accueil de la plateforme le PROMET depuis toujours dans
son aperçu d'arborescence, et il n'existait pas.

Le nom `AGENTS.md` remplace `CLAUDE.md` : le frontend peut être écrit par
claude-code, codex ou gemini (point 69), et nommer ce fichier d'après un seul
d'entre eux en fait un fichier que les deux autres ne lisent pas.
"""

import os

from .fondations import AGENTS_FILENAME, README_FILENAME

PROJECT_CLAUDE_MD_MARKER = "<!-- généré par monl — orchestration frontend -->"
PROJECT_README_MARKER = "<!-- généré par monl — démarrage du projet -->"

#: L'ancien nom, gardé pour le déplacement des projets déjà compilés. Il ne
#: doit PAS disparaître de la source : sans lui, un CLAUDE.md produit par une
#: version antérieure resterait à côté d'AGENTS.md, périmé et sans un mot.
LEGACY_AGENTS_FILENAME = "CLAUDE.md"

PROJECT_CLAUDE_MD = """{marker}
# {app} — project memory for agents

This folder is a monl project: the backend (app.py, schema.sql) is GENERATED
from the spec `spec.ml` (or the .ml file present) — the spec is the source
of truth, the backend a sealed artifact.

## Your role here: the FRONTEND, nothing else

- Read `docs/FRONTEND_PROMPT.md`: it is the complete contract (routes, auth,
  fields, design direction). Machine-readable version:
  `frontend_contract.json`, at the root.
- Write ONLY in `frontend/`, entry point `frontend/index.html`.
  Static, SELF-CONTAINED HTML/CSS/JS (no CDN, no external script — the
  condition for the smoke test to be able to verify it).
- To EVOLVE an existing frontend after a spec change, read
  `docs/FRONTEND_UPDATE_PROMPT.md` (generated by `monl update`) and modify
  what exists; do not rewrite from scratch.

## Absolutely forbidden

NEVER modify: the `.ml` spec, `app.py`, `schema.sql`, `sandbox_ai.py`
(if it exists), `frontend_contract.json`, `monl.json`, `.jwt_secret`, or
anything in `docs/`. If the backend seems to need a change, it is the SPEC
that must evolve (by the user), followed by `monl update`.

## Check your work

`monl run . --check` (if `monl` is on the PATH) runs the full check: static
consistency + behavioral smoke test (ephemeral server, contract routes
exercised over real HTTP, your `index.html` executed in jsdom). Fix until
it is green — `monl run .` will refuse to start while the smoke test fails.
"""

PROJECT_README = """{marker}
# {app}

Application produced by [monl](https://github.com/Bodichane/monl-compiler) from
the spec `{spec}`. The backend is **compiled**: it is not written by hand.

## Getting started

```bash
pip install -r requirements.txt
uvicorn serve:app --host 127.0.0.1 --port 8000
```

The API answers on <http://127.0.0.1:8000> — the root redirects to `/docs`,
its interactive documentation, where every route can be tried. The frontend
is served at `/site` if it exists; otherwise `/site` returns 404 and the API
still works.

On first start, the server writes `.jwt_secret` itself (permissions 0600).
**In production**, set `MONL_ENV=production` and supply `MONL_JWT_SECRET`:
the server then refuses to start without it, rather than making up a secret
that would change at every restart and invalidate every session.

## Administration

```bash
python3 manage.py --help
```

Create the accounts of roles that do not register online, list them, delete
them. It is the only legitimate path for those roles.

## What is in the folder

| File | Role |
| --- | --- |
| `{spec}` | **the source of truth** — it is what you modify |
| `app.py`, `schema.sql`, `manage.py`, `serve.py` | generated, sealed |
| `frontend_contract.json` | the machine interface: routes, fields, rights |
| `docs/` | what is meant to be read — frontend brief and visual direction |
| `frontend/` | the interface, written by you or by an AI |
| `requirements.txt`, `Dockerfile` | deployment, editable |

## Evolving it

Modify the spec, then `monl update .`: the backend is recompiled and the
report names what changes for the frontend (routes, fields, access, locks).
Never modify `app.py` directly — the next compilation would overwrite it.
"""


def _ecrire_si_a_nous(path, marker, contenu):
    """N'écrase jamais un document repris en main par l'utilisateur.

    L'absence du marqueur signe un fichier que quelqu'un a écrit ou réécrit :
    le remplacer effacerait son travail sans le dire.
    """
    if os.path.exists(path):
        with open(path, encoding="utf-8") as fh:
            if marker not in fh.read():
                return False
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(contenu)
    return True


def write_project_claude_md(app_name, output_dir, spec_name="spec.ml", auth_features=None):
    """Écrit AGENTS.md et README.md du PROJET (pas ceux du dépôt monl)."""
    _ecrire_si_a_nous(
        os.path.join(output_dir, AGENTS_FILENAME),
        PROJECT_CLAUDE_MD_MARKER,
        PROJECT_CLAUDE_MD.format(marker=PROJECT_CLAUDE_MD_MARKER, app=app_name))
    readme = PROJECT_README.format(marker=PROJECT_README_MARKER, app=app_name,
                                  spec=spec_name)
    if (auth_features or {}).get("totp"):
        readme += (
            "\n## TOTP recovery\n\n"
            "`python3 manage.py totp-reset <identifier>` clears TOTP and revokes "
            "all account sessions. This is the operator recovery path. Email "
            "password reset preserves TOTP. TOTP enable requires the current "
            "password and a valid code; all devices must log in again with TOTP.\n"
        )
    _ecrire_si_a_nous(
        os.path.join(output_dir, README_FILENAME),
        PROJECT_README_MARKER,
        readme)
