"""The serving wrapper, shared by 'monl compile', 'monl run' and the smoke
test.

WHY THIS MODULE EXISTS (brick 13, point 83). The wrapper lived in cli.py,
and the smoke test ran `app:app` — so it exercised NEITHER the mount of
frontend/ on /site NOR that of the assets. "Served" was checked nowhere:
only the eye, on the page, would have seen a misplaced mount.

Having the smoke test check it required both layers to share the same
text. Duplicating it would have created two wrappers to drift — exactly
what the project refuses elsewhere (PAYMENT_*_COLUMN, _compute_route_map).
But smoke_test is imported by cli, so the reverse would make a cycle:
hence this module, a deliberate LEAF that imports nothing from the
project."""

SERVE_WRAPPER = '''"""Wrapper generated by monl — do not edit.
Mounts the frontend produced by the AI (frontend/) at /site, without modifying
app.py (the backend stays a sealed artifact of the compiler)."""
import os
import sys

from fastapi.staticfiles import StaticFiles
from app import app

# BRICK 13 (point 83): the assets supplied by the HUMAN live outside
# frontend/, because that folder is renamed on every build by 'monl frontend'
# and its allowlist does not accept .jpg — photos dropped there ended up in
# frontend.precedent/ without a word.
#
# The mount must come BEFORE the /site one: Starlette tests routes in
# registration order, and '/site' mounted first would swallow
# '/site/<folder>/…' to look for it in frontend/, where it is not.
_ASSETS_DIR = {assets_dir!r}
if _ASSETS_DIR and os.path.isdir(_ASSETS_DIR):
    app.mount("/site/" + _ASSETS_DIR,
              StaticFiles(directory=_ASSETS_DIR), name="assets")

# The frontend is built AFTER compilation ('monl frontend'), so this wrapper
# is emitted before frontend/ exists and must start anyway: otherwise the
# image produced by 'monl compile' would not start at all. But the absence is
# SAID — a silent 404 on /site is precisely the defect this wrapper exists to
# prevent.
if os.path.isdir("frontend"):
    app.mount("/site", StaticFiles(directory="frontend", html=True), name="site")
else:
    print("[monl] frontend/ missing: the API answers, /site will return 404. "
          "Build the interface with 'monl frontend'.", file=sys.stderr)
'''


def render_wrapper(assets_dir=None):
    """The text of the serve.py to write into a project.

    'assets_dir' is the folder declared by the spec, or None: in that case the
    wrapper mounts only frontend/, exactly as before brick 13."""
    return SERVE_WRAPPER.format(assets_dir=assets_dir)
