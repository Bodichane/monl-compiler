"""What a pass must be able to do, and what the driver expects of it."""

from collections.abc import Sequence
from dataclasses import dataclass
from typing import Protocol


class ValidationContext(Protocol):
    """The surface the current passes need."""

    def _validate_constraints_of_field(self) -> None: ...

    def _validate_control_access(self) -> None: ...

    def _validate_rule_public(self) -> None: ...

    def _validate_rules_once_per(self) -> None: ...

    def _validate_rule_restrictedto(self) -> None: ...

    def _validate_fields_masques(self) -> None: ...

    def _validate_fields_categorized(self) -> None: ...

    def _validate_fields_generated(self) -> None: ...

    def _validate_fields_timestamped(self) -> None: ...

    def _validate_fields_numbered(self) -> None: ...

    def _validate_fields_enumerated(self) -> None: ...

    def _validate_capabilities_of_list(self) -> None: ...

    def _validate_requires_own_and_payable(self) -> None: ...

    def _validate_fields_derives(self) -> None: ...

    def _validate_fields_aggregated(self) -> None: ...

    def _validate_security_calculations_payment(self) -> None: ...

    def _validate_effects_counters(self) -> None: ...

    def _validate_owner_payment(self) -> None: ...

    def _validate_rules_release(self) -> None: ...

    def _validate_workflows_and_collisions(self) -> None: ...

    def _validate_fields_uploaded(self) -> None: ...

    def _validate_ui_overrides(self) -> None: ...

    def _validate_landing(self) -> None: ...

    def _validate_capabilities(self) -> None: ...

    def _validate_rules_message(self) -> None: ...

    def _validate_assets_and_seeds(self) -> None: ...

    def _validate_migrations(self) -> None: ...

    def _validate_rule_after_payment(self) -> None: ...

    def _audit_security_rules(self) -> list[str]: ...

    def _audit_self_registration(self) -> list[str]: ...

class ValidationPass(Protocol):
    name: str

    def run(self, context: ValidationContext) -> list[str]: ...

@dataclass(frozen=True, slots=True)
class ValidationPipeline:
    passes: Sequence[ValidationPass]

    def run(self, context: ValidationContext) -> list[str]:
        reports = []
        for validation_pass in self.passes:
            reports.extend(validation_pass.run(context))
        return reports
