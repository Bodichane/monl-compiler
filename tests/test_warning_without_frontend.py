"""Issue #83: what `monl run --check` announces about a project WITHOUT a
frontend must be what a real server serves.

The warning promised "its only generated pages (landing, /app, /docs)" while
the frontend generated by monl disappeared at point 41: `/` answered 307 to
/docs and `/app` a JSON 404, which the user took for a failure. The witness
does not compare the message to an expected sentence — it ASKS the server for
each path the message cites, and checks the answer against what is said.
"""

import re
import urllib.error
import urllib.request

from monl.cli import check_coherence, compile_project
from tests.support.server import uvicorn_server


class _WithoutRedirection(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, *args, **kwargs):
        return None


_OPENER = urllib.request.build_opener(_WithoutRedirection)


def _status(url):
    try:
        with _OPENER.open(url, timeout=5) as r:
            return r.status, r.headers.get("Location")
    except urllib.error.HTTPError as e:
        with e:
            return e.code, e.headers.get("Location")


def _warning_without_frontend(project):
    ok, errors, warnings = check_coherence(str(project))
    assert ok, errors
    found = [a for a in warnings if "frontend/" in a]
    assert len(found) == 1, warnings
    return found[0]


def _cited_paths(message):
    """The URL paths the message names (`/`, `/docs`, `/site/`…).

    A path is a slash at the start of a word; `frontend/` is not one (the slash
    is at the end of the word), which is the reason for the anchor."""
    return sorted(set(re.findall(r"(?<![\w.])/[a-z_]*/?", message)))


def test_each_path_announced_without_frontend_answers_as_announced(tmp_path, capsys):
    compile_project("exemples/02_boutique.ml", str(tmp_path))
    capsys.readouterr()
    assert not (tmp_path / "frontend").exists()

    message = _warning_without_frontend(tmp_path)
    paths = _cited_paths(message)
    # Non-emptiness: without an extracted path, the loop below would check
    # nothing and return green (point 161). We do NOT require a precise list:
    # the server, not a sentence copied here, judges each path.
    assert paths, message

    with uvicorn_server(str(tmp_path), module="serve:app") as base:
        for path in paths:
            status, destination = _status(base + path)
            if path == "/site/":
                # The message says /site/ answers 404 without an interface: it
                # must be TRUE, otherwise it promises a failure that does not
                # happen.
                assert status == 404, (path, status)
            elif path == "/":
                assert status in (302, 307) and destination == "/docs", (
                    path, status, destination)
            else:
                assert status == 200, (
                    f"the warning cites {path}, which answers {status}: "
                    f"a user opening it believes their deployment is broken")


def test_a_frontend_calling_app_is_reported(tmp_path, capsys):
    """`/app` was among the consistency check's "known" prefixes, a leftover of
    the frontend removed at point 41: a frontend calling it was not reported,
    while the server answers 404 there."""
    compile_project("exemples/02_boutique.ml", str(tmp_path))
    capsys.readouterr()
    (tmp_path / "frontend").mkdir()
    (tmp_path / "frontend" / "index.html").write_text(
        "<!doctype html><title>t</title>"
        "<script>fetch('/app/tableau').then(r => r.json())</script>",
        encoding="utf-8")

    _ok, _errors, warnings = check_coherence(str(tmp_path))
    missing = [a for a in warnings
               if "paths missing from the contract" in a]
    assert missing and "/app" in missing[0], warnings
